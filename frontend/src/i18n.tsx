function getInitialLocale(): Locale {
  const saved = window.localStorage.getItem(STORAGE_KEY);
  return isLocale(saved) ? saved : 'en';
}

function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'zh-CN' || value === 'zh-TW';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      localeLabels,
      setLocale: setLocaleState,
      t: (key, values) => {
        const template = messages[locale][key] ?? messages.en[key] ?? key;
        if (!values) return template;
        return Object.entries(values).reduce(
          (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
          template,
        );
      },
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside I18nProvider');
  }
  return context;
}

export function LanguageSelector({ compact = false }: { compact?: boolean }) {
  const { locale, localeLabels, setLocale, t } = useI18n();
  return (
    <label className={compact ? 'block' : 'flex items-center gap-2'}>
      {!compact && <span className="font-label-caps text-[10px] uppercase text-outline">{t('language')}</span>}
      <select
        aria-label={t('language')}
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
        className="w-full rounded border border-outline-variant bg-surface-container-high px-2 py-1.5 text-xs text-on-surface outline-none transition-colors focus:border-secondary-container/60"
      >
        {(Object.keys(localeLabels) as Locale[]).map((item) => (
          <option key={item} value={item} className="bg-surface text-on-surface">
            {localeLabels[item]}
          </option>
        ))}
      </select>
    </label>
  );
}
